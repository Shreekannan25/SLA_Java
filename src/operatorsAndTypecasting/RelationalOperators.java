package operatorsAndTypecasting;

public class RelationalOperators {
	
	    public static void main(String[] args) {

	        int a = 20, b = 10;

	        System.out.println("Equal = " + (a == b));
	        System.out.println("Greater = " + (a > b));
	        System.out.println("Smaller = " + (a < b));
	    }
	
}
